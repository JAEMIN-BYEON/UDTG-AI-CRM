// 다른 지역으로 확정 판별되는 표기가 토큰에 있으면 키워드 오인 매칭을 차단
// (예: "부산 강서구"의 '강서'가 서울로, "경기광주"의 '광주'가 호남 광주로 잡히는 것 방지)
const EXCLUSIVE_MARKERS: Record<string, string[]> = {
  서울: ["부산", "인천", "대구", "경기"],
  광주: ["경기"],
  경기남부: ["전라", "광주광역시", "부산", "서울"],
  경기북부: ["부산", "서울"],
};

export function regionMatches(desired: string, listingRegionCsv: string): boolean {
  const tokens = listingRegionCsv.split(",").map((t) => t.trim()).filter(Boolean);
  const keywords = REGION_KEYWORDS[desired] ?? [];
  const excludes = EXCLUSIVE_MARKERS[desired] ?? [];

  return tokens.some((t) => {
    // 다른 지역으로 확정되는 표기가 있으면 우선 배제 (예: 광주 선택 시 "경기광주" 차단)
    if (excludes.some((x) => t.includes(x))) return false;
    // 기존 방식(양방향 부분일치) 유지 — 자유 텍스트 입력·과거 데이터 호환
    if (t.includes(desired) || desired.includes(t)) return true;
    return keywords.some((k) => t.includes(k));
  });
}
